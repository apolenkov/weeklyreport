const DEV_SESSION: UserSession = {
  userId: "a0000000-0000-4000-8000-000000000099",
  email: "head@customreport.local",
  name: "Антон К.",
  role: "head",
  activeReportId: "a0000000-0000-4000-8000-000000000001",
  activeReportSectionId: null,
};

/**
 * UFB-047 / Phase 48-A: 5-second TTL cache for the Organization singleton.
 *
 * The org row is read on every authenticated tRPC call to hydrate
 * `session.organization`. A short TTL keeps admin renames visible within
 * ~5s without hammering Postgres on every request. Cache miss path is
 * a single primary-key lookup, so cold reads are cheap.
 */
const ORG_CACHE_TTL_MS = 5_000;
let orgCache: {
  value: { shortName: string; fullName: string };
  expiresAt: number;
} | null = null;

/**
 * Phase 32-B1 (H-04): synthetic session created when an inbound cookie is
 * a valid PDF-export JWT (kind='pdf-export'). The session must satisfy
 * `userSessionSchema` (uuid userId, email, etc.) so existing middlewares
 * keep their shape contract. Read-only restrictions live on TrpcContext
 * (`isPdfExport` + `pdfReportId`) and are enforced by `pdfExportGuardMiddleware`
 * in trpc.middleware, NOT by mutating the role.
 */
const PDF_EXPORT_SYNTHETIC_USER_ID = "a0000000-0000-4000-8000-0000000pdfwk";
const PDF_EXPORT_SYNTHETIC_EMAIL = "pdf-worker@internal.customreport.local";

function buildPdfExportSession(reportId: string): UserSession {
  return {
    userId: PDF_EXPORT_SYNTHETIC_USER_ID,
    email: PDF_EXPORT_SYNTHETIC_EMAIL,
    name: "PDF Worker",
    // viewer is the narrowest role that can read a published report via the
    // service-layer filters. The pdfExportGuard middleware further restricts
    // procedure paths to `weeklyReport.get` and `archive.detail`.
    role: "viewer",
    activeReportId: reportId,
    activeReportSectionId: null,
  };
}

export type TrpcContext = {
  session: UserSession | null;
  logger: AppLogger;
  /** Request correlation id from the x-request-id header, generated by the
   * CorrelationIdMiddleware before tRPC context construction. */
  correlationId?: string;
  /** Optional in direct unit callers; real HTTP contexts always receive it. */
  prisma?: PrismaService;
  /**
   * AUTH-08 (Phase 29-01): structured audit channel for security-relevant
   * events (login success/fail, logout, role-denied). Built once per
   * factory; the same instance is shared across all requests because the
   * underlying AppLogger is request-agnostic (correlation IDs flow via
   * nestjs-cls).
   */
  auditLogger: AuditLogger;
  /**
   * Client-perceived IP read from `req.ip` (Express trust-proxy aware).
   * Threat-model T3: never read from raw X-Forwarded-For; this field is
   * the canonical seam audit emits read from.
   */
  ip: string;
  /**
   * Phase 32-B1 (H-04): true when the inbound cookie verified as a
   * PDF-export-scoped JWT (rather than a regular session JWT). When true,
   * the synthetic session is restricted to a hard-coded allowlist of read
   * procedures keyed on `pdfReportId`; all other procedures throw FORBIDDEN
   * via the `pdfExportGuard` middleware applied to every protected procedure
   * helper.
   */
  isPdfExport: boolean;
  /**
   * Phase 32-B1 (H-04): the reportId from the verified PDF JWT claim, used
   * by pdfExportGuard to assert the procedure input's reportId matches.
   * `null` whenever `isPdfExport === false`.
   */
  pdfReportId: string | null;
};

function readRequestId(header: string | string[] | undefined): string {
  if (Array.isArray(header)) return header[0] ?? "no-context";
  return header ?? "no-context";
}

export function createContextFactory(
  _app: INestApplication,
  logger: AppLogger,
) {
  const authController = createAuthController(process.env);
  // Resolve PrismaService once (not per request) from the NestJS DI container.
  const prisma = _app.get(PrismaService);
  const auditLogger = createAuditLogger(logger);
  // A2 (UAT-v7 2026-05-12): Redis-backed session revocation fast path.
  // Constructed once; the underlying ioredis client uses lazyConnect so it
  // does not block startup when Redis is unavailable.
  const sessionRevocation = new SessionRevocationService();

  return async ({ req }: CreateExpressContextOptions): Promise<TrpcContext> => {
    const ip = req.ip ?? "unknown";
    const correlationId = readRequestId(req.headers?.["x-request-id"]);
    const token = req.cookies?.["customreport_session"] as string | undefined;

    if (token) {
      try {
        const session = authController.verifySessionToken(token);

        // A2 (UAT-v7 2026-05-12): revocation check.
        // 1. Fast path — Redis revoked set (sadd'd on deactivateUser).
        //    fail-open: a Redis outage returns false and falls to Prisma.
        // 2. Authoritative path — isActive column in Prisma User row.
        //    Checked inline here so a stale JWT cannot bypass deactivation.
        const revoked = await sessionRevocation.isRevoked(session.userId);
        if (revoked) {
          // Do NOT fall through to PDF path; treat as invalid token.
          throw new Error("session revoked");
        }
        const userRow = await prisma.user.findUnique({
          where: { id: session.userId },
          select: { isActive: true },
        });
        if (userRow && !userRow.isActive) {
          throw new Error("user deactivated");
        }

        const resolved = await resolveSectionId(session, prisma);
        const hydrated = await hydrateViewerGroupAccess(resolved, prisma);
        const withOrg = await hydrateOrganization(hydrated, prisma);
        return {
          session: withOrg,
          logger,
          correlationId,
          prisma,
          auditLogger,
          ip,
          isPdfExport: false,
          pdfReportId: null,
        };
      } catch {
        // Regular session token invalid/expired (or revoked/deactivated) --
        // try the PDF-export verifier path before falling through to
        // dev-mode / null.
      }

      // Phase 32-B1 (H-04): PDF worker authentication path. The Playwright
      // browser injects a 5-min JWT signed by `signPdfExportToken` carrying
      // `{ reportId, kind: 'pdf-export' }`. We verify against
      // PDF_EXPORT_JWT_SECRET (different secret than session JWT). On
      // success we synthesize a viewer-shaped session bound to the reportId
      // claim; the `pdfExportGuard` middleware enforces the
      // procedure-allowlist + reportId-match constraint.
      try {
        const pdfClaims = verifyPdfExportToken(token);
        return {
          session: buildPdfExportSession(pdfClaims.reportId),
          logger,
          correlationId,
          prisma,
          auditLogger,
          ip,
          isPdfExport: true,
          pdfReportId: pdfClaims.reportId,
        };
      } catch {
        // Not a PDF token either -- fall through to dev-mode / null.
      }
    }

    // AUTH-01 / Phase 29-04 (CC-1, CC-2):
    //  - DEV_SESSION fallback ONLY fires when NODE_ENV !== 'production' AND a
    //    dev-auth flag is set. A boot-time fence in `lib/dev-auth-fence.ts`
    //    refuses to start the API at all if either flag is true under
    //    NODE_ENV=production, so this branch is doubly defended.
    //  - AUTH_DEV_MODE=true: legacy dev-loop convenience (preserved for the
    //    docker-compose dev stack and local pnpm dev runs).
    //  - AUTH_DEV_MODE_ALLOW_TEST=true: staged path enabling the integration
    //    suite + PDF worker to operate against a "real" tRPC context without
    //    flipping production. Retired entirely once the mock IdP container
    //    follow-up lands (deferred from this plan due to no Docker network).
    const isNonProd = process.env["NODE_ENV"] !== "production";
    const devModeEnabled = isNonProd && process.env["AUTH_DEV_MODE"] === "true";
    const allowTest =
      isNonProd && process.env["AUTH_DEV_MODE_ALLOW_TEST"] === "true";
    if (devModeEnabled || allowTest) {
      const devResolved = await resolveSectionId({ ...DEV_SESSION }, prisma);
      const devHydrated = await hydrateViewerGroupAccess(devResolved, prisma);
      const devWithOrg = await hydrateOrganization(devHydrated, prisma);
      return {
        session: devWithOrg,
        logger,
        correlationId,
        prisma,
        auditLogger,
        ip,
        isPdfExport: false,
        pdfReportId: null,
      };
    }

    return {
      session: null,
      logger,
      correlationId,
      prisma,
      auditLogger,
      ip,
      isPdfExport: false,
      pdfReportId: null,
    };
  };
}

/**
 * DEV_SESSION sets activeReportSectionId to null because it is a head user.
 * For lead users in production, the JWT will contain the sectionId.
 * This dynamic lookup serves as a fallback for any session missing the sectionId
 * (e.g. dev mode, or token issued before the section was created).
 *
 * Heads have no ReportSection of their own, so findFirst returns null and the
 * session keeps activeReportSectionId = null. That is correct -- head users
 * use the review.* endpoints which filter by reportId, not sectionId.
 */
/**
 * UFB-040 / Phase 46-01: viewer sessions need an up-to-date list of granted
 * `ReportingGroup.id`s for groupScopeFilter. We hydrate per-request rather
 * than baking into the JWT because admin can grant/revoke at any time and
 * stale JWTs would leak (or block) access.
 *
 * No-op for non-viewer roles to keep the hot path cheap.
 */
async function hydrateViewerGroupAccess(
  session: UserSession,
  prisma: PrismaService,
): Promise<UserSession> {
  if (session.role !== "viewer") return session;
  const grants = await prisma.viewerGroupAccess.findMany({
    where: { viewerUserId: session.userId },
    select: { groupId: true },
  });
  session.viewerGroupAccess = grants.map((g) => g.groupId);
  return session;
}

/**
 * UFB-047 / Phase 48-A: hydrate the singleton organization identity onto
 * the session so authenticated routes can render the brand without a
 * second round-trip. We DO NOT bake this into the JWT for two reasons:
 *   1. JWTs are 1h-lived; admin renames would not propagate until refresh.
 *   2. Adding required fields to the JWT shape would invalidate every
 *      in-flight cookie on deploy.
 *
 * A 5-second module-level TTL cache (defined above) absorbs the read load —
 * the org row changes on the order of months, not seconds, so a stale
 * 5s window is acceptable. The cache is process-local; in a multi-replica
 * deploy each replica eventually picks up the new value within TTL.
 */
async function hydrateOrganization(
  session: UserSession,
  prisma: PrismaService,
): Promise<UserSession> {
  const now = Date.now();
  if (!orgCache || orgCache.expiresAt < now) {
    // UFB-060: seed defaults are generic — concrete tenant brand stays
    // in the seed file / admin-edited Organization row, never in code.
    const row = await prisma.organization.upsert({
      where: { id: "singleton" },
      create: {
        id: "singleton",
        shortName: DEFAULT_ORGANIZATION_IDENTITY.shortName,
        fullName: DEFAULT_ORGANIZATION_IDENTITY.fullName,
      },
      update: {},
      select: { shortName: true, fullName: true },
    });
    orgCache = {
      value: { shortName: row.shortName, fullName: row.fullName },
      expiresAt: now + ORG_CACHE_TTL_MS,
    };
  }
  session.organization = orgCache.value;
  return session;
}

async function resolveSectionId(
  session: UserSession,
  prisma: PrismaService,
): Promise<UserSession> {
  if (
    !session.activeReportSectionId &&
    session.activeReportId &&
    session.userId
  ) {
    const section = await prisma.reportSection.findFirst({
      where: {
        reportId: session.activeReportId,
        authorId: session.userId,
      },
      select: { id: true },
    });
    if (section) {
      session.activeReportSectionId = section.id;
    }
  }
  return session;
}
