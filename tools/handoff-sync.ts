/**
 * REL-05 (Phase 28-04) — handoff-sync tool
 *
 * Reads `/CHECKLIST.md`, extracts unticked items (`- [ ]` lines), and
 * rewrites the `## Pending Manual Smoke` section in `/HANDOFF.md`.
 *
 * Idempotent: rerunning produces the same output. Section is replaced in
 * place, bounded by `<!-- handoff-sync:start -->` and
 * `<!-- handoff-sync:end -->` markers; if absent, the section is appended
 * at the end of HANDOFF.md.
 *
 * Usage: `pnpm gsd:checklist:sync` (alias for `pnpm tsx tools/handoff-sync.ts`).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const CHECKLIST_PATH = resolve(process.cwd(), 'CHECKLIST.md');
const HANDOFF_PATH = resolve(process.cwd(), 'HANDOFF.md');
const START_MARKER = '<!-- handoff-sync:start -->';
const END_MARKER = '<!-- handoff-sync:end -->';

export interface ChecklistItem {
  id: string;
  gate: 'manual' | 'CI';
  description: string;
}

export function parseUntickedItems(checklist: string): ChecklistItem[] {
  const items: ChecklistItem[] = [];
  // Match `- [ ] <DOMAIN>-<TOPIC>-<NNN> [manual|CI] — <description>`.
  // Em-dash `—` is intentional — CHECKLIST.md uses U+2014.
  const re =
    /^- \[ \] ([A-Z]+-[A-Z]+-\d{3}) \[(manual|CI)\] [——-] (.+)$/gm;
  let match: RegExpExecArray | null;
  while ((match = re.exec(checklist)) !== null) {
    items.push({
      id: match[1] ?? '',
      gate: (match[2] as 'manual' | 'CI'),
      description: match[3] ?? '',
    });
  }
  return items;
}

export function buildSection(items: ChecklistItem[]): string {
  const manual = items.filter((i) => i.gate === 'manual');
  const ci = items.filter((i) => i.gate === 'CI');
  const lines: string[] = [];
  lines.push('## Pending Manual Smoke');
  lines.push('');
  lines.push(
    'Auto-generated by `pnpm gsd:checklist:sync` from `/CHECKLIST.md`. Edit the checklist, not this section.',
  );
  lines.push('');
  lines.push(`### Manual (${manual.length})`);
  for (const item of manual) {
    lines.push(`- [ ] **${item.id}** — ${item.description}`);
  }
  lines.push('');
  lines.push(`### CI-gated (${ci.length})`);
  for (const item of ci) {
    lines.push(`- [ ] **${item.id}** — ${item.description}`);
  }
  lines.push('');
  return lines.join('\n');
}

export function rewriteHandoff(handoff: string, generatedSection: string): string {
  const block = `${START_MARKER}\n${generatedSection}${END_MARKER}\n`;
  const startIdx = handoff.indexOf(START_MARKER);
  const endIdx = handoff.indexOf(END_MARKER);

  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    // Replace the existing block, including the trailing newline if present.
    const tailStart = endIdx + END_MARKER.length;
    const trailingNl = handoff[tailStart] === '\n' ? 1 : 0;
    return handoff.slice(0, startIdx) + block + handoff.slice(tailStart + trailingNl);
  }

  // Append. Ensure exactly one blank line separator.
  const sep = handoff.endsWith('\n\n') ? '' : handoff.endsWith('\n') ? '\n' : '\n\n';
  return handoff + sep + block;
}

export function main(): void {
  if (!existsSync(CHECKLIST_PATH)) {
    process.stderr.write(`handoff-sync: CHECKLIST.md not found at ${CHECKLIST_PATH}\n`);
    process.exit(1);
  }
  if (!existsSync(HANDOFF_PATH)) {
    process.stderr.write(`handoff-sync: HANDOFF.md not found at ${HANDOFF_PATH}\n`);
    process.exit(1);
  }
  const checklist = readFileSync(CHECKLIST_PATH, 'utf8');
  const handoff = readFileSync(HANDOFF_PATH, 'utf8');
  const items = parseUntickedItems(checklist);
  const section = buildSection(items);
  const next = rewriteHandoff(handoff, section);
  if (next !== handoff) {
    writeFileSync(HANDOFF_PATH, next);
    process.stdout.write(
      `handoff-sync: rewrote ${HANDOFF_PATH} (${items.length} items)\n`,
    );
  } else {
    process.stdout.write(
      `handoff-sync: HANDOFF.md already up to date (${items.length} items)\n`,
    );
  }
}

const invokedDirectly =
  typeof process.argv[1] === 'string' &&
  (process.argv[1].endsWith('handoff-sync.ts') ||
    process.argv[1].endsWith('handoff-sync.js'));
if (invokedDirectly) {
  main();
}
